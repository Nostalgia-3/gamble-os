function createPaletteFile(path: string, colors: number[]) {
    const dv = new DataView(new Uint8Array(64).buffer);

    for(let i=0;i<colors.length;i++) {
        dv.setUint32(i*4, colors[i], true);
    }

    Deno.writeFileSync(path, new Uint8Array(dv.buffer));
}

